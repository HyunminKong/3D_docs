"""Pose-verified cross-episode A→B→A' benchmark construction.

This module intentionally builds a *cross-episode* revisit benchmark.  A
within-trajectory query is useful for measuring ordinary streaming forgetting,
but cannot validate retrieval of a long-term adaptation from an earlier drive.

Input scenes use the repository's converted ``opencv_cameras.json`` format.
Camera centres are recovered from ``w2c`` and all matching is restricted to a
metadata location when one is available.  Splits are connected components of
the physical-overlap graph, preventing the same road segment from appearing in
both train and test.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Iterable

import numpy as np


@dataclass(frozen=True)
class Segment:
    scene: str
    frames: tuple[int, ...]
    query_frames: tuple[int, ...]


@dataclass(frozen=True)
class RevisitEpisode:
    """One source stream A→B and a physically matched target revisit A'."""

    episode_id: str
    split: str
    source_scene: str
    target_scene: str
    location: str
    min_overlap_m: float
    a: Segment
    b: Segment
    a_prime: Segment


def _centres(camera_json: Path) -> np.ndarray:
    frames = json.loads(camera_json.read_text())["frames"]
    result = []
    for frame in frames:
        w2c = np.asarray(frame["w2c"], dtype=np.float64)
        result.append(-w2c[:3, :3].T @ w2c[:3, 3])
    return np.stack(result)


def _sample(start: int, stop: int, count: int) -> tuple[int, ...]:
    if stop <= start:
        raise ValueError(f"empty segment [{start}, {stop})")
    count = min(count, stop - start)
    return tuple(np.linspace(start, stop - 1, count).round().astype(int).tolist())


def _segment(scene: str, start: int, stop: int, context: int, queries: int) -> Segment:
    """Disjoint context and held-out query samples inside one temporal span."""
    total = stop - start
    if total < context + queries:
        raise ValueError(f"{scene}: span has {total} frames, need {context + queries}")
    all_ids = _sample(start, stop, context + queries)
    return Segment(scene=scene, frames=all_ids[:context], query_frames=all_ids[context:])


def _components(nodes: Iterable[str], edges: Iterable[tuple[str, str]]) -> list[set[str]]:
    parent = {node: node for node in nodes}

    def find(x: str) -> str:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for a, b in edges:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
    groups: dict[str, set[str]] = {}
    for node in parent:
        groups.setdefault(find(node), set()).add(node)
    return list(groups.values())


def _split_component(component: set[str], seed: int) -> str:
    token = "|".join(sorted(component)).encode()
    bucket = int(hashlib.sha1(token + str(seed).encode()).hexdigest(), 16) % 10
    return "test" if bucket == 0 else "val" if bucket == 1 else "train"


def _load_locations(selection: Path | None) -> dict[str, str]:
    if selection is None:
        return {}
    raw = json.loads(selection.read_text())
    return {entry["scene"]: entry.get("location", "unknown") for entry in raw["units"]}


def build_manifest(
    root: str | Path,
    *,
    selection: str | Path | None = None,
    overlap_m: float = 2.0,
    context_frames: int = 8,
    query_frames: int = 4,
    a_prime_radius_fraction: float = 0.15,
    seed: int = 0,
) -> list[RevisitEpisode]:
    """Build directional pose-overlap episodes from converted nuScenes scenes.

    ``selection`` should be the pose-map metadata generated by
    ``oracle/select_2x2.py`` for nuScenes.  Without it, all scenes are treated
    as one location; this is safe only when the input root already contains one
    map coordinate frame.
    """
    root = Path(root)
    locations = _load_locations(Path(selection) if selection else None)
    files = sorted(root.glob("*/opencv_cameras.json"))
    scenes = {path.parent.name: path for path in files}
    centres = {name: _centres(path) for name, path in scenes.items()}
    names = sorted(scenes)

    pairs: list[tuple[str, str, float, int, int]] = []
    edges: list[tuple[str, str]] = []
    for i, source in enumerate(names):
        for target in names[i + 1:]:
            if locations and locations.get(source) != locations.get(target):
                continue
            distances = np.linalg.norm(
                centres[source][:, None] - centres[target][None, :], axis=-1
            )
            flat = int(np.argmin(distances))
            src_idx, tgt_idx = np.unravel_index(flat, distances.shape)
            minimum = float(distances[src_idx, tgt_idx])
            if minimum <= overlap_m:
                pairs.append((source, target, minimum, int(src_idx), int(tgt_idx)))
                edges.append((source, target))

    components = _components(names, edges)
    split_of = {scene: _split_component(component, seed)
                for component in components for scene in component}
    episodes: list[RevisitEpisode] = []
    def local_segment(scene: str, anchor: int) -> Segment:
        n = len(centres[scene])
        radius = max(context_frames + query_frames, int(n * a_prime_radius_fraction))
        start = max(0, min(anchor - radius // 2, n - radius))
        return _segment(scene, start, start + radius, context_frames, query_frames)

    def distant_segment(scene: str, anchor: int) -> Segment:
        """Choose B from the temporal end opposite A, with no frame overlap."""
        n = len(centres[scene])
        radius = max(context_frames + query_frames, int(n * a_prime_radius_fraction))
        start = 0 if anchor >= n // 2 else n - radius
        return _segment(scene, start, start + radius, context_frames, query_frames)

    for source, target, minimum, source_anchor, target_anchor in pairs:
        location = locations.get(source, "unknown")
        for left, right, left_anchor, right_anchor in (
            (source, target, source_anchor, target_anchor),
            (target, source, target_anchor, source_anchor),
        ):
            try:
                a = local_segment(left, left_anchor)
                b = distant_segment(left, left_anchor)
                a_prime = local_segment(right, right_anchor)
            except ValueError:
                continue
            episodes.append(RevisitEpisode(
                episode_id=f"{left}__{right}",
                split=split_of[left], source_scene=left, target_scene=right,
                location=location, min_overlap_m=minimum, a=a, b=b, a_prime=a_prime,
            ))
    return episodes


class RevisitBenchmark:
    """Lightweight manifest view, deliberately independent of any backbone."""

    def __init__(self, episodes: Iterable[RevisitEpisode]):
        self.episodes = list(episodes)

    def split(self, name: str) -> list[RevisitEpisode]:
        return [episode for episode in self.episodes if episode.split == name]

    def summary(self) -> dict[str, int]:
        return {name: len(self.split(name)) for name in ("train", "val", "test")}

    def write(self, path: str | Path) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps([asdict(item) for item in self.episodes], indent=2))
